const fs = require('fs')
const path = require('path')
const ts = require('typescript')

const root = path.resolve(__dirname, '..')

function read(relativePath) {
  return fs.readFileSync(path.join(root, relativePath), 'utf8')
}

function stripImports(source) {
  const lines = source.split(/\r?\n/)
  const kept = []
  let skippingImport = false

  for (const line of lines) {
    if (!skippingImport && line.trimStart().startsWith('import ')) {
      skippingImport = !line.includes(' from ')
      continue
    }

    if (skippingImport) {
      if (line.includes(' from ')) skippingImport = false
      continue
    }

    kept.push(line)
  }

  return kept.join('\n')
}

function prepareSource(source) {
  return stripImports(source)
    .replace(/^export\s+/gm, '')
    .replace(/^export\s+\{[^}]+\}\s*$/gm, '')
}

const source = `
${prepareSource(read('lib/scheduler/scoring.ts'))}

${prepareSource(read('lib/scheduler/rotationOptimizer.ts'))}

${prepareSource(read('lib/scheduler/oneClickOptimization.ts'))}

self.onmessage = function(event) {
  const requestId = event.data.requestId
  const input = event.data.input
  try {
    const results = runOneClickOptimization(input, function(progress) {
      self.postMessage({ requestId, type: 'progress', progress })
    })
    self.postMessage({ requestId, type: 'done', results })
  } catch (error) {
    self.postMessage({
      requestId,
      type: 'error',
      error: error && error.message ? error.message : 'Failed to optimize schedule',
    })
  }
}
`

const output = ts.transpileModule(source, {
  compilerOptions: {
    target: ts.ScriptTarget.ES2018,
    module: ts.ModuleKind.None,
    removeComments: false,
  },
}).outputText

const outDir = path.join(root, 'public', 'workers')
fs.mkdirSync(outDir, { recursive: true })
fs.writeFileSync(
  path.join(outDir, 'one-click-optimization-worker.js'),
  `// Generated by scripts/build-one-click-worker.cjs. Do not edit by hand.\n${output}`,
  'utf8'
)
